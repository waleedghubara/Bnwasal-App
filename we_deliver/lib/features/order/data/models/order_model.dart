import '../../domain/entities/order.dart';

class OrderModel extends OrderEntity {
  const OrderModel({
    required super.id,
    required super.orderNumber,
    required super.details,
    required super.storeDescription,
    super.notes,
    required super.deliveryAddress,
    required super.phone,
    required super.clientName,
    required super.orderPrice,
    required super.deliveryFee,
    super.latitude,
    super.longitude,
    super.merchantLatitude,
    super.merchantLongitude,
    super.driverLatitude,
    super.driverLongitude,
    super.startLatitude,
    super.startLongitude,
    required super.status,
    required super.createdAt,
    super.captainId,
    super.captainName,
    super.captainAvatar,
    super.captainPhone,
    super.merchantId,
    super.merchantName,
    super.merchantPhone,
    super.merchantAvatar,
    super.merchantAddress,
    super.captainApprovalStatus,
    super.isPaid,
    super.directPayment,
  });

  factory OrderModel.fromJson(Map<String, dynamic> json) {
    return OrderModel(
      id: json['id']?.toString() ?? '',
      orderNumber: json['orderNumber']?.toString() ?? '',
      details: json['details']?.toString() ?? '',
      storeDescription: json['storeDescription']?.toString() ?? '',
      notes: json['notes']?.toString(),
      deliveryAddress: json['deliveryAddress']?.toString() ?? '',
      phone: json['phone']?.toString() ?? '',
      clientName: json['clientName']?.toString() ?? '',
      orderPrice: (json['orderPrice'] as num?)?.toDouble() ?? 0.0,
      deliveryFee: (json['deliveryFee'] as num?)?.toDouble() ?? 0.0,
      latitude: (json['latitude'] as num?)?.toDouble(),
      longitude: (json['longitude'] as num?)?.toDouble(),
      merchantLatitude: (json['merchantLatitude'] as num?)?.toDouble(),
      merchantLongitude: (json['merchantLongitude'] as num?)?.toDouble(),
      driverLatitude: (json['driverLatitude'] as num?)?.toDouble(),
      driverLongitude: (json['driverLongitude'] as num?)?.toDouble(),
      startLatitude: (json['startLatitude'] as num?)?.toDouble(),
      startLongitude: (json['startLongitude'] as num?)?.toDouble(),
      status: json['status']?.toString() ?? '',
      createdAt: json['createdAt'] != null
          ? DateTime.parse(json['createdAt'])
          : DateTime.now(),
      captainId: json['captainId']?.toString(),
      captainName: json['captainName']?.toString(),
      captainAvatar: json['captainAvatar']?.toString(),
      captainPhone: json['captainPhone']?.toString(),
      merchantId: json['merchantId']?.toString(),
      merchantName: json['merchantName']?.toString(),
      merchantPhone: json['merchantPhone']?.toString(),
      merchantAvatar: json['merchantAvatar']?.toString(),
      merchantAddress: json['merchantAddress']?.toString() ?? json['fromAddress']?.toString(),
      captainApprovalStatus: json['captainApprovalStatus']?.toString(),
      isPaid: json['isPaid'] == 1 || json['isPaid'] == true,
      directPayment: json['directPayment'] as Map<String, dynamic>?,
    );
  }

  factory OrderModel.fromEntity(OrderEntity order) {
    return OrderModel(
      id: order.id,
      orderNumber: order.orderNumber,
      details: order.details,
      storeDescription: order.storeDescription,
      notes: order.notes,
      deliveryAddress: order.deliveryAddress,
      phone: order.phone,
      clientName: order.clientName,
      orderPrice: order.orderPrice,
      deliveryFee: order.deliveryFee,
      latitude: order.latitude,
      longitude: order.longitude,
      merchantLatitude: order.merchantLatitude,
      merchantLongitude: order.merchantLongitude,
      driverLatitude: order.driverLatitude,
      driverLongitude: order.driverLongitude,
      startLatitude: order.startLatitude,
      startLongitude: order.startLongitude,
      status: order.status,
      createdAt: order.createdAt,
      captainId: order.captainId,
      captainName: order.captainName,
      captainAvatar: order.captainAvatar,
      captainPhone: order.captainPhone,
      merchantId: order.merchantId,
      merchantName: order.merchantName,
      merchantPhone: order.merchantPhone,
      merchantAvatar: order.merchantAvatar,
      merchantAddress: order.merchantAddress,
      captainApprovalStatus: order.captainApprovalStatus,
      isPaid: order.isPaid,
      directPayment: order.directPayment,
    );
  }
}
