  static String? getZone(String? area) {
    if (area == null) return null;
    final cleanArea = area.trim();
    // try exact match first
    if (areaToZone.containsKey(cleanArea)) {
      return areaToZone[cleanArea];
    }
    // try partial match
    for (final entry in areaToZone.entries) {
      if (cleanArea.contains(entry.key) || entry.key.contains(cleanArea)) {
        return entry.value;
      }
    }
    return null;
  }

  static String? matchExcelArea(String? area) {
    if (area == null) return null;
    final cleanArea = area.trim();

    // try exact match first
    for (final excelArea in excelPrices.keys) {
      if (excelArea == cleanArea) {
        return excelArea;
      }
    }

    // try partial contains match
    for (final excelArea in excelPrices.keys) {
      if (cleanArea.contains(excelArea) || excelArea.contains(cleanArea)) {
        return excelArea;
      }
    }

    return null;
  }

  static double? getSuggestedPrice(String? fromArea, String? toArea) {
    if (fromArea == null || toArea == null) return null;

    final matchedFrom = matchExcelArea(fromArea);
    final matchedTo = matchExcelArea(toArea);

    if (matchedFrom != null && matchedTo != null) {
      final price = excelPrices[matchedFrom]?[matchedTo];
      if (price != null) {
        return price;
      }
    }

    // Fallback to legacy zone pricing if not found in Excel matrix
    final fromZone = getZone(fromArea);
    final toZone = getZone(toArea);

    if (fromZone == null || toZone == null) return null;
    return pricingMatrix[fromZone]?[toZone];
  }
