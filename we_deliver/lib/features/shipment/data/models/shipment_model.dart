import '../../domain/entities/shipment.dart';

class ShipmentModel extends Shipment {
  const ShipmentModel({
    required super.id,
    required super.shipmentNumber,
    super.title,
    required super.fromAddress,
    required super.toAddress,
    super.fromGovernorate,
    super.fromArea,
    super.toGovernorate,
    super.toArea,
    required super.status,
    super.clientName,
    super.clientAvatar,
    super.clientPhone,
    super.driverName,
    super.driverAvatar,
    super.driverPhone,
    super.driverId,
    super.merchantId,
    super.estimatedTime,
    required super.price,
    super.negotiatedPrice,
    super.weight,
    super.notes,
    super.isFragile,
    super.isWithoutAdvance,
    super.images,
    super.imageUrls,
    super.toLatitude,
    super.toLongitude,
    super.merchantLatitude,
    super.merchantLongitude,
    super.driverLatitude,
    super.driverLongitude,
    super.startLatitude,
    super.startLongitude,
    super.captainApprovalStatus,
    required super.createdAt,
    super.isPaid,
    super.directPayment,
    super.couponCode,
  });

  factory ShipmentModel.fromJson(Map<String, dynamic> json) {
    return ShipmentModel(
      id: json['id']?.toString() ?? '',
      shipmentNumber: json['shipmentNumber']?.toString() ?? '',
      title: json['title'],
      fromAddress: json['fromAddress']?.toString() ?? '',
      toAddress: json['toAddress']?.toString() ?? '',
      fromGovernorate: json['fromGovernorate'],
      fromArea: json['fromArea'],
      toGovernorate: json['toGovernorate'],
      toArea: json['toArea'],
      status: json['status']?.toString() ?? '',
      clientName: json['clientName'],
      clientAvatar: json['clientAvatar'],
      clientPhone: json['clientPhone'],
      driverName: json['driverName'],
      driverAvatar: json['driverAvatar'],
      driverPhone: json['driverPhone'],
      driverId: json['captainId']?.toString(),
      merchantId: json['merchantId']?.toString(),
      estimatedTime: json['estimatedTime'],
      price: (json['price'] as num?)?.toDouble() ?? 0.0,
      negotiatedPrice: (json['negotiatedPrice'] as num?)?.toDouble(),
      weight: (json['weight'] as num?)?.toDouble(),
      notes: json['notes'],
      isFragile: json['isFragile'] == 1 || json['isFragile'] == true,
      isWithoutAdvance: json['isWithoutAdvance'] == 1 || json['isWithoutAdvance'] == true,
      imageUrls: json['images'] != null ? List<String>.from(json['images']) : null,
      toLatitude: (json['toLatitude'] as num?)?.toDouble(),
      toLongitude: (json['toLongitude'] as num?)?.toDouble(),
      merchantLatitude: (json['merchantLatitude'] as num?)?.toDouble(),
      merchantLongitude: (json['merchantLongitude'] as num?)?.toDouble(),
      driverLatitude: (json['driverLatitude'] as num?)?.toDouble(),
      driverLongitude: (json['driverLongitude'] as num?)?.toDouble(),
      startLatitude: (json['startLatitude'] as num?)?.toDouble(),
      startLongitude: (json['startLongitude'] as num?)?.toDouble(),
      captainApprovalStatus: json['captainApprovalStatus']?.toString(),
      createdAt: json['createdAt'] != null
          ? DateTime.parse(json['createdAt'])
          : DateTime.now(),
      isPaid: json['isPaid'] == 1 || json['isPaid'] == true,
      directPayment: json['directPayment'] as Map<String, dynamic>?,
      couponCode: json['couponCode']?.toString(),
    );
  }

  factory ShipmentModel.fromEntity(Shipment shipment) {
    return ShipmentModel(
      id: shipment.id,
      shipmentNumber: shipment.shipmentNumber,
      title: shipment.title,
      fromAddress: shipment.fromAddress,
      toAddress: shipment.toAddress,
      fromGovernorate: shipment.fromGovernorate,
      fromArea: shipment.fromArea,
      toGovernorate: shipment.toGovernorate,
      toArea: shipment.toArea,
      status: shipment.status,
      clientName: shipment.clientName,
      clientAvatar: shipment.clientAvatar,
      clientPhone: shipment.clientPhone,
      driverName: shipment.driverName,
      driverAvatar: shipment.driverAvatar,
      driverPhone: shipment.driverPhone,
      driverId: shipment.driverId,
      merchantId: shipment.merchantId,
      estimatedTime: shipment.estimatedTime,
      price: shipment.price,
      negotiatedPrice: shipment.negotiatedPrice,
      weight: shipment.weight,
      notes: shipment.notes,
      isFragile: shipment.isFragile,
      isWithoutAdvance: shipment.isWithoutAdvance,
      images: shipment.images,
      imageUrls: shipment.imageUrls,
      toLatitude: shipment.toLatitude,
      toLongitude: shipment.toLongitude,
      merchantLatitude: shipment.merchantLatitude,
      merchantLongitude: shipment.merchantLongitude,
      driverLatitude: shipment.driverLatitude,
      driverLongitude: shipment.driverLongitude,
      startLatitude: shipment.startLatitude,
      startLongitude: shipment.startLongitude,
      captainApprovalStatus: shipment.captainApprovalStatus,
      createdAt: shipment.createdAt,
      isPaid: shipment.isPaid,
      directPayment: shipment.directPayment,
      couponCode: shipment.couponCode,
    );
  }
}


